/**
 * O corpus de inocentes do filtro do que o fã publica (docs/arquitetura-api.md,
 * 30.11): textos que nunca podem ser barrados, conferidos contra a lista de
 * verdade (as chaves do `terms.ts`) pelo `content-filter/terms.test.ts`. Fica
 * fora do build. Nenhum termo da lista entra aqui: só o que precisa passar.
 *
 * Os municípios vêm do IBGE (`ibge-municipios.tsv`, baixado da API oficial,
 * servicodados.ibge.gov.br, com o ok do dono em 13/10/2026, e copiado como
 * veio). Os prenomes e os sobrenomes vão escritos à mão: nada mais é baixado.
 */

/** Um município: o nome, como o IBGE escreve, e a UF. */
export type Municipality = { readonly name: string; readonly uf: string };

/** Os 5.571 municípios do IBGE, uma linha por município ("Nome", tabulação e a UF). */
export function ibgeMunicipalities(): Municipality[] {
  const text = readFileSync(resolve(__dirname, 'ibge-municipios.tsv'), 'utf8');
  return text
    .split(/\r?\n/)
    .filter((line) => line !== '')
    .map((line) => {
      const [name = '', uf = ''] = line.split('\t');
      return { name, uf };
    });
}

